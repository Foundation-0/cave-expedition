"""Scale flow of PREREG 4.1: block averaging by 2, order-4 pattern classes at lag 1, and its transfer.

Definitions used (Amendment 1):
- levels l = 0, 1, 2 ... by block averaging by 2 applied separately to each contiguous valid run (no average crosses a
  gap), as long as a level still gives at least 12 segments;
- at each level, segments are cut as in section 7 (blocks of N + 128, the every-k rule, the rank offset rule);
- the 9 features of a unit: the frequency, over all windows, of order-4 patterns at lag 1 summed over the 8 classes of
  untied patterns that map to each other under time reversal and polarity flip, plus a ninth class of every window
  with a tie. Pseudocount 1/2 for each of the 75 patterns, denominator count + 75/2. Each of the 9 frequencies is
  standardised against the pool of 99 IAAFT surrogates of that unit;
- aligned level = l - round(log2 tau0); levels -3 to +3 are kept, 63 features;
- a unit is a (level, segment) pair. It fills the 9 entries of its own aligned level. S_B(w) is the mean over B's
  aligned levels of the mean over that level's units of w dotted with the unit's features."""
import numpy as np
import patterns
import segments
import seeds
import stats43
import transfer

MIN_SEG = 12
FLOW_LEVELS = list(range(-3, 4))  # aligned levels kept
NF = 9
POOL_N = 75


def class_lists():
    """9 index lists over the 75 order-4 patterns: 8 orbit classes of the 24 untied patterns under the group
    generated by time reversal and polarity flip, and the 51 tied patterns as the ninth class."""
    T = patterns.tables(4)
    rev, comp, untied = T["rev"], T["comp"], T["untied"]
    seen = {}
    for k in range(T["n"]):
        if untied[k]:
            orb = tuple(sorted({k, int(rev[k]), int(comp[k]), int(rev[int(comp[k])])}))
            seen[orb] = True
    cls = [list(c) for c in sorted(seen)]
    if len(cls) != 8:
        raise RuntimeError("expected 8 classes of order-4 patterns, got %d" % len(cls))
    cls.append([k for k in range(T["n"]) if not untied[k]])
    return cls


def block_average(x, runs=None, op="mean"):
    """Block averaging (op 'mean') or block maxima (op 'max', Law 2b instance B) by 2, within each contiguous run
    (a, b). Returns (series, runs of the result)."""
    x = np.asarray(x, dtype=np.float64)
    if runs is None:
        runs = [(0, len(x))]
    parts, new_runs, pos = [], [], 0
    for (a, b) in runs:
        seg = x[a:b]
        m = (len(seg) // 2) * 2
        pr = seg[:m].reshape(-1, 2)
        y = pr.mean(axis=1) if op == "mean" else pr.max(axis=1)
        parts.append(y)
        new_runs.append((pos, pos + len(y)))
        pos += len(y)
    return np.concatenate(parts), new_runs


def level_streams(x, N=4096, pad=segments.PAD, start=0, runs=None, op="mean"):
    """Levels l = 0, 1, ... while the level gives at least 12 segments. Returns list of (l, series, runs)."""
    x = np.asarray(x, dtype=np.float64)
    if runs is None:
        runs = [(0, len(x))]
    out = []
    l = 0
    cur, cr = x, runs
    while True:
        st, J, k = segments.select_blocks(len(cur), N, pad, 32, start)
        if len(st) < MIN_SEG:
            break
        out.append((l, cur, cr))
        cur, cr = block_average(cur, cr, op)
        l += 1
    return out


def unit_features(C4, freq_map=None):
    """C4: (P, 75) order-4 lag-1 counts, row 0 real. Returns z (P, 9) standardised class frequencies and S2 (P,)
    sums of squared standardised features. freq_map (default identity) is applied to the frequencies before
    standardisation (Law 2b instance H uses the square root)."""
    cls = class_lists()
    c = np.asarray(C4, dtype=np.float64)
    tot = c.sum(axis=1) + POOL_N / 2.0
    fr = np.stack([(c[:, ix].sum(axis=1) + len(ix) / 2.0) / tot for ix in cls], axis=1)
    if freq_map is not None:
        fr = freq_map(fr)
    z, _ = stats43.loo_standardise(fr)
    return z, (z * z).sum(axis=1)


def analyse_unit(seg, key, M=99, freq_map=None):
    pool, it, cv = stats43.make_pool(seg, key, M, "iaaft")
    C4, _ = patterns.counts_batch(pool, 4, 1)
    z, S2 = unit_features(C4, freq_map)
    n_ge = int((S2[1:] >= S2[0]).sum())
    return {"z": z[0].copy(), "S2": float(S2[0]), "n_ge": n_ge, "departs": n_ge <= 4}


def stream_units(x, prefix, N=4096, start=0, runs=None, op="mean", freq_map=None, jobs_map=None, M=99):
    """All units of a stream: for each level, cut segments (section 7) and analyse each. prefix = (instrument, split,
    net). jobs_map: a map function (callable like par.pmap) to run unit analyses in parallel.
    Returns list of dicts with l, seg index and the unit result."""
    lv = level_streams(x, N, segments.PAD, start, runs, op)
    jobs, meta = [], []
    for (l, ser, rr) in lv:
        cut = segments.cut_segments(ser, N=N, start=start)
        for q, c in enumerate(cut):
            if c["seg"] is None:
                continue
            jobs.append((c["seg"], prefix + ("flow-L%d-q%d" % (l, q),), M, freq_map))
            meta.append((l, q))
    return jobs, meta


def finish_units(res, meta):
    return [dict(l=l, q=q, **r) for (l, q), r in zip(meta, res)]


def flow_vectors(units, shift):
    """Per aligned level (-3..3): mean of the unit features at that level. Returns (V (7, 9) level means,
    count (7,) units per aligned level). Levels with no unit have count 0."""
    V = np.zeros((7, NF))
    cnt = np.zeros(7, dtype=np.int64)
    for u in units:
        a = u["l"] - shift
        if -3 <= a <= 3:
            V[a + 3] += u["z"]
            cnt[a + 3] += 1
    for k in range(7):
        if cnt[k] > 0:
            V[k] /= cnt[k]
    return V, cnt


def flow_template(units_fit, shift):
    """Template of A: per aligned level, the mean over that level's fit units (so each level counts equally),
    all 63 entries scaled to unit length."""
    V, cnt = flow_vectors(units_fit, shift)
    return transfer.build_template(V.reshape(1, -1)), (cnt > 0)


def flow_target(units_verdict, shift):
    """B's side. g such that S_B(w) = w . g is the mean over B's populated aligned levels of w_level . mean unit
    features at that level. Returns g (63,) and the populated-level mask (7,)."""
    V, cnt = flow_vectors(units_verdict, shift)
    nl = int((cnt > 0).sum())
    if nl == 0:
        return np.zeros(7 * NF), cnt > 0
    return (V / nl).reshape(-1), cnt > 0


def flow_pop_mask(levA, levB):
    both = np.asarray(levA, dtype=bool) & np.asarray(levB, dtype=bool)
    return np.repeat(both, NF)


def flow_transfer(units_fit_A, shiftA, units_verdict_B, shiftB, rng, R=transfer.R_DETECTORS):
    w, levA = flow_template(units_fit_A, shiftA)
    g, levB = flow_target(units_verdict_B, shiftB)
    res = transfer.transfer_test("flow", w, g, flow_pop_mask(levA, levB), rng, R)
    return transfer.apply_floor(res, "flow")


def level_departure(units_verdict):
    """Per flow level l: (units, departing units). A unit departs if its sum of squared standardised features is
    exceeded or equalled by at most 4 of its 99 surrogates (p <= 0.05)."""
    out = {}
    for u in units_verdict:
        a = out.setdefault(u["l"], [0, 0])
        a[0] += 1
        a[1] += 1 if u["departs"] else 0
    return out
