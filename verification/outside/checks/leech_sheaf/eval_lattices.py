"""Independent rebuild of the AUDIT-020R lattices from a different Golay code (evaluator check).

Checks: the lattices generated by the target's BW16 and Leech bases have the stated
determinant, index, even-unimodular Gram, and exactly 4,320 and 196,560 minimal vectors
(Fincke-Pohst, every hit rechecked exactly). Leech is identified by Conway's uniqueness
(even unimodular, rank 24, no roots). BW16 is identified as a section of a Leech lattice
built here from the cyclic quadratic-residue code mod 23, under an explicit coordinate
permutation. Contact counts then follow: 32 (4320 - 30) = 137,280 and 48 (196560 - 46)
= 9,432,672.
Backs: VERDICTS.md section 1, row "Barnes-Wall and Leech realizations and arcs (020R)",
and the AUDIT-020R realization witnesses in section 2.
Needs: Python 3, numpy, a clone of the target at the head of draft PR 106
(first argument, or environment variable INCENTRE_LATTICES_PR106).
Run: python3 -I -B eval_lattices.py /path/to/incentre-lattices
Time: about 25 seconds. No random numbers are used. Writes no files.
"""
import itertools
import json
import os
import sys
from fractions import Fraction

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from eval_common import team_data, int_row_basis, det_frac, inv_frac, fail, analyse  # noqa: E402

report = {}


# ---------------- 1. my Golay code: cyclic QR code mod 23, extended ----------------
QR23 = sorted({(i * i) % 23 for i in range(1, 23)})


def span_gf2(rows):
    basis = []
    for r in rows:
        v = int("".join(map(str, r)), 2)
        for b in basis:
            v = min(v, v ^ b)
        if v:
            basis.append(v)
    return basis


golay = None
for support in (set(QR23), set(range(1, 23)) - set(QR23), set(QR23) | {0}, (set(range(1, 23)) - set(QR23)) | {0}):
    g = [1 if i in support else 0 for i in range(23)]
    shifts = [[g[(j - s) % 23] for j in range(23)] for s in range(23)]
    basis = span_gf2(shifts)
    if len(basis) != 12:
        continue
    words = set()
    for mask in range(1 << 12):
        v = 0
        for k in range(12):
            if mask >> k & 1:
                v ^= basis[k]
        words.add(v)
    ext = []
    for v in words:
        bits = [int(c) for c in format(v, "023b")]
        ext.append(tuple(bits + [sum(bits) % 2]))
    wd = {}
    for w in ext:
        wd[sum(w)] = wd.get(sum(w), 0) + 1
    if wd == {0: 1, 8: 759, 12: 2576, 16: 759, 24: 1}:
        golay = ext
        break
if golay is None:
    fail("no Golay code found")
GOLAY = set(golay)
report["my_golay"] = "cyclic QR mod 23, extended; weights {0:1,8:759,12:2576,16:759,24:1}"


def in_my_leech(x):
    """x in Z^24: Conway's description, my Golay code (scaled so norm = |x|^2/8)."""
    par = x[0] & 1
    if any((a & 1) != par for a in x):
        return False
    if sum(x) % 8 != (4 * par) % 8:
        return False
    for k in range(4):
        s = tuple(1 if (a - k) % 4 == 0 else 0 for a in x)
        if par == 0 and k in (0, 2) or par == 1 and k in (1, 3):
            if s not in GOLAY and tuple(1 - b for b in s) not in GOLAY:
                return False
    return True


# ---------------- 2. lattices generated by the team's bases (analyse is in eval_common.py) ----------------

C16 = team_data("C2_16_WITNESS")   # = 2*C
U24 = team_data("U24_WITNESS")     # = 4*C
r16, B16, min16, L16 = analyse("BW16", 16, C16, 2)
report["BW16_team_basis"] = r16
print("BW16", r16, flush=True)
r24, B24, min24, L24 = analyse("Leech", 24, U24, 4)
report["Leech_team_basis"] = r24
print("Leech", r24, flush=True)

# Leech identification: even unimodular rank 24 with no vectors of sqrt2-norm 2 => Leech (Conway 1969)
report["Leech_identified_by_Conway_uniqueness"] = (
    r24["even"] and r24["det_sqrt2_gram"] == "1" and "2" not in r24["short_vector_counts_by_sqrt2norm"]
    and r24["short_vector_counts_by_sqrt2norm"].get("4") == 196560)

# my Leech: check that the team's minimal vectors (scaled to my convention) are NOT required to be in
# my Leech (different Golay code => different coordinates).  Instead identify BW16 explicitly:
# section of MY Leech supported off one octad.
octad = next(w for w in golay if sum(w) == 8)
off = [i for i in range(24) if octad[i] == 0]
code16 = sorted({tuple(w[i] for i in off) for w in golay if all(w[i] == 0 for i in range(24) if octad[i])})
report["section_code_size"] = len(code16)
wts = {}
for c in code16:
    wts[sum(c)] = wts.get(sum(c), 0) + 1
report["section_code_weights"] = wts
# find 4 weight-8 words whose coordinate patterns are all distinct -> bijection coords -> F_2^4
w8 = [c for c in code16 if sum(c) == 8]
perm = None
for quad in itertools.combinations(w8, 4):
    pats = [tuple(q[i] for q in quad) for i in range(16)]
    if len(set(pats)) == 16:
        perm = [pats[i][0] * 1 + pats[i][1] * 2 + pats[i][2] * 4 + pats[i][3] * 8 for i in range(16)]
        break
if perm is None:
    fail("no RM labelling")
# RM(1,4) in the team's indexing: affine functions of the bits of the coordinate index
rm = set()
for a in range(16):
    for c in (0, 1):
        rm.add(tuple(((bin(a & i).count("1") + c) % 2) for i in range(16)))
mapped = set()
for c in code16:
    v = [0] * 16
    for i in range(16):
        v[perm[i]] = c[i]
    mapped.add(tuple(v))
report["section_code_maps_onto_RM14_by_explicit_permutation"] = (mapped == rm)


# BW16 team definition: Gamma16 = 1/2 {x : x mod 2 in RM(1,4), sum x = 0 mod 4}
def in_team_bw16_def(x2):
    return tuple(a % 2 for a in x2) in rm and sum(x2) % 4 == 0


# section of my Leech off the octad, in my scaling x (norm |x|^2/8); map to Gamma16 (norm |.|^2/4 for 2*v):
# a Leech vector x supported off the octad has all entries even (odd type has full support);
# Gamma (min norm 2) scaling: w = x/4 ; doubled team coords x2 = 2w = x/2.
basis_ok = all(in_team_bw16_def(b) for b in B16)  # team basis vectors are in the RM definition
# every one of my section's generators maps into the team's Gamma16 definition and vice versa (both directions):
sec_gens = []
for c in code16:
    if sum(c) == 8:
        x = [0] * 24
        for k, i in enumerate(off):
            x[i] = 2 * c[k]
        # fix sum = 0 mod 8: weight-8 with all +2: sum 16 ok
        sec_gens.append(x)
for i in range(16):
    for j in range(i + 1, 16):
        x = [0] * 24
        x[off[i]] = 4
        x[off[j]] = 4
        sec_gens.append(x)
        y = [0] * 24
        y[off[i]] = 4
        y[off[j]] = -4
        sec_gens.append(y)
if not all(in_my_leech(x) for x in sec_gens):
    fail("section generators not in my Leech")


def to_team(x):
    v = [0] * 16
    for k, i in enumerate(off):
        v[perm[k]] = x[i] // 2
    return v


sec_team = [to_team(x) for x in sec_gens]
report["my_section_generators_in_team_BW16_def"] = all(in_team_bw16_def(v) for v in sec_team)
Bsec = int_row_basis(sec_team)
report["my_section_covolume_in_team_coords_x2"] = str(abs(det_frac(Bsec)))
report["team_Gamma_gen16_covolume_x2"] = str(abs(det_frac(B16)))
# same covolume and team basis inside the same definition => Gamma_gen16 = permuted section of my Leech
# (need also: team basis spans a lattice containing section: check each section generator in span of B16)
B16inv = inv_frac(B16)
inside = all(all((sum(Fraction(v[k]) * B16inv[k][j] for k in range(16))).denominator == 1 for j in range(16))
             for v in sec_team)
report["my_section_inside_team_Gamma_gen16"] = inside
report["team_basis_rows_in_RM_definition"] = basis_ok

print(json.dumps(report, indent=1, sort_keys=True))

