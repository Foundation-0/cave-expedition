HASH_SEED = 12345


def load_tables():
    return {name: team_data(name) for name in ("C2_16_WITNESS", "U24_WITNESS", "X0_24_INT_256")}


# ---------------- exact integer linear algebra ----------------

def frac_inverse(M):
    n = len(M)
    A = [[Fraction(M[i][j]) for j in range(n)] + [Fraction(int(i == j)) for j in range(n)] for i in range(n)]
    det = Fraction(1)
    for k in range(n):
        piv = next((i for i in range(k, n) if A[i][k] != 0), None)
        need(piv is not None, "singular")
        if piv != k:
            A[k], A[piv] = A[piv], A[k]
            det = -det
        pv = A[k][k]
        det *= pv
        A[k] = [x / pv for x in A[k]]
        for i in range(n):
            if i != k and A[i][k] != 0:
                f = A[i][k]
                A[i] = [a - f * b for a, b in zip(A[i], A[k])]
    return [row[n:] for row in A], det


def adj_mod(Mint):
    """Integer matrix M (k*L). Returns D = det M (int) and Adj mod |D| as Python ints,
    so that y M^{-1} = (y Adj)/D."""
    inv, det = frac_inverse(Mint)
    need(det.denominator == 1, "det not integral")
    D = int(det)
    adj = [[inv[i][j] * D for j in range(len(Mint))] for i in range(len(Mint))]
    for row in adj:
        for x in row:
            need(x.denominator == 1, "adjugate not integral")
    m = abs(D)
    return D, [[int(x) % m for x in row] for row in adj]


# ---------------- framework objects ----------------

class Framework:
    def __init__(self, n, k, C_k):
        """C_k = k*C integer matrix; L = 2I + C; bar vectors c_i = rows of C."""
        self.n, self.k = n, k
        self.Ck = [list(r) for r in C_k]
        self.Lk = [[(2 * k if i == j else 0) + C_k[i][j] for j in range(n)] for i in range(n)]
        self.D, adj = adj_mod(self.Lk)
        self.mod = abs(self.D)
        need(self.mod < 2 ** 45, "modulus too large for int64 path")
        self.adj = np.array(adj, dtype=np.int64)
        # motif points P = {+e_i, -e_i}; index 2i -> +e_i, 2i+1 -> -e_i
        self.P = []
        for i in range(n):
            for s in (1, -1):
                v = [0] * n
                v[i] = s
                self.P.append(v)

    def cls(self, Yk):
        """classes of points y (given as integer array k*y, shape (N,n)) modulo Lambda."""
        return (Yk.astype(np.int64) @ self.adj) % self.mod

    def setup_cosets(self):
        Pk = np.array([[self.k * x for x in p] for p in self.P], dtype=np.int64)
        self.Pcls = self.cls(Pk)
        keys = {tuple(r) for r in self.Pcls.tolist()}
        need(len(keys) == 2 * self.n, "motif points not distinct mod Lambda")
        # closure: subgroup generated by p - e0 must be exactly {p - e0}
        e0 = self.Pcls[0]
        diffs = {tuple(((r - e0) % self.mod).tolist()) for r in self.Pcls}
        grp = set(diffs)
        frontier = list(grp)
        while frontier:
            new = []
            for a in frontier:
                for b in diffs:
                    c = tuple((x + y) % self.mod for x, y in zip(a, b))
                    if c not in grp:
                        grp.add(c)
                        new.append(c)
            frontier = new
            need(len(grp) <= 4 * self.n, "closure too large")
        need(grp == diffs, "P - e0 + Lambda is not closed under addition")
        # det check: covolume(Gamma) = det(L)/2n
        self.detL = Fraction(self.D, self.k ** self.n)
        # random scalar hash for class lookup
        rng = np.random.default_rng(HASH_SEED)
        self.rho = rng.integers(1, 2 ** 15, size=self.n, dtype=np.int64)
        self.hmod = (1 << 31) - 1
        ph = self.hash(self.Pcls)
        need(len(set(ph.tolist())) == 2 * self.n, "hash collision on motif classes")
        self.hash_to_p = {h: i for i, h in enumerate(ph.tolist())}
        return {"det_L": str(self.detL), "index_Gamma_over_Lambda": len(grp)}

    def hash(self, cl):
        return ((cl % self.hmod) * self.rho).sum(axis=1) % self.hmod

    def member(self, Zk):
        """z in Gamma  <=>  z + e0 in P + Lambda."""
        e0k = np.zeros(self.n, dtype=np.int64)
        e0k[0] = self.k
        cl = self.cls(Zk + e0k)
        h = self.hash(cl)
        ok = np.zeros(len(Zk), dtype=bool)
        for hv, pi in self.hash_to_p.items():
            sel = h == hv
            if sel.any():
                ok[sel] = (cl[sel] == self.Pcls[pi]).all(axis=1)
        return ok


def all_sign_vectors(support_size):
    return np.array(list(itertools.product((1, -1), repeat=support_size)), dtype=np.int64)


def enumerate_shape(n, values_abs, signs=True):
    """all integer vectors whose multiset of nonzero |entries| is values_abs."""
    groups = {}
    for v in values_abs:
        groups[v] = groups.get(v, 0) + 1
    items = sorted(groups.items())
    m = len(values_abs)
    sv = all_sign_vectors(m)

    def place(idx, remaining):
        if idx == len(items):
            yield []
            return
        val, cnt = items[idx]
        for comb in itertools.combinations(remaining, cnt):
            rest = [r for r in remaining if r not in comb]
            for tail in place(idx + 1, rest):
                yield [(p, val) for p in comb] + tail

    out = []
    for assignment in place(0, list(range(n))):
        base = np.zeros((len(sv), n), dtype=np.int64)
        for j, (p, val) in enumerate(assignment):
            base[:, p] = sv[:, j] * val
        out.append(base)
    arr = np.concatenate(out, axis=0)
    need(len(np.unique(arr, axis=0)) == len(arr), "duplicate candidates")
    return arr


def bw16_min_vectors(F):
    """k=2. All integer u=2z of norm 8 are shapes {2,2},{2,1,1,1,1},{1^8}: exhaustive."""
    n = 16
    res = {}
    found = []
    for shape in ([2, 2], [2, 1, 1, 1, 1], [1] * 8):
        cand = enumerate_shape(n, shape)
        ok = F.member(cand)
        res[str(shape)] = [int(len(cand)), int(ok.sum())]
        found.append(cand[ok])
    # shorter vectors: norms 2,4,6 in u-scale
    short = 0
    for shape in ([1, 1], [2], [1] * 4, [2, 1, 1], [1] * 6):
        cand = enumerate_shape(n, shape)
        short += int(F.member(cand).sum())
    W = np.concatenate(found, axis=0)
    return W, {"shapes": res, "count": int(len(W)), "shorter_nonzero_vectors": short}


def hnf_rows(gens):
    """row-style integer HNF basis (Python ints) of the lattice spanned by gens."""
    rows = [list(map(int, g)) for g in gens]
    n = len(rows[0])
    basis = []
    col = 0
    while rows and col < n:
        nz = [r for r in rows if r[col] != 0]
        z = [r for r in rows if r[col] == 0]
        while len(nz) > 1:
            nz.sort(key=lambda r: abs(r[col]))
            p = nz[0]
            new = [p]
            for r in nz[1:]:
                q = r[col] // p[col]
                rr = [a - q * b for a, b in zip(r, p)]
                if rr[col] != 0:
                    new.append(rr)
                elif any(rr):
                    z.append(rr)
            nz = new
        if nz:
            basis.append(nz[0])
        rows = [r for r in z if any(r)]
        col += 1
    return basis


def leech_min_vectors(F):
    """k=4. Derive parity structure and code from Gamma itself, then enumerate."""
    n = 24
    gens = [row[:] for row in F.Lk]
    for p in F.P:
        gens.append([4 * (p[j] - F.P[0][j]) for j in range(n)])
    B = hnf_rows(gens)
    need(len(B) == n, "rank deficiency")
    det_basis = 1
    for i in range(n):
        det_basis *= B[i][i]
    covol_k = abs(det_basis)  # covolume of 4*Gamma
    # uniform parity of every basis vector
    par = []
    for b in B:
        bits = {x & 1 for x in b}
        need(len(bits) == 1, "mixed parity basis vector")
        par.append(bits.pop())
    odd_idx = [i for i in range(n) if par[i] == 1]
    need(odd_idx, "no odd vectors")
    j0 = odd_idx[0]
    even_gens = [B[i] for i in range(n) if par[i] == 0]
    even_gens += [[a + b for a, b in zip(B[i], B[j0])] for i in odd_idx if i != j0]
    even_gens += [[2 * a for a in B[j0]]]
    code_gens = [[(x // 2) & 1 for x in g] for g in even_gens]
    # span over F2
    code = {tuple([0] * n)}
    for g in code_gens:
        code |= {tuple(a ^ b for a, b in zip(c, g)) for c in code}
    wts = {}
    for c in code:
        w = sum(c)
        wts[w] = wts.get(w, 0) + 1
    x0 = tuple(((x - 1) // 2) & 1 for x in B[j0])
    out = []
    counts = {}
    # type 1
    cand = enumerate_shape(n, [4, 4])
    ok = F.member(cand)
    counts["(4,4)"] = [int(len(cand)), int(ok.sum())]
    out.append(cand[ok])
    # type 2 on weight-8 codewords
    octads = [c for c in code if sum(c) == 8]
    sv = all_sign_vectors(8)
    cands = []
    for c in octads:
        supp = [i for i in range(n) if c[i]]
        base = np.zeros((256, n), dtype=np.int64)
        base[:, supp] = 2 * sv
        cands.append(base)
    cand = np.concatenate(cands, axis=0)
    ok = F.member(cand)
    counts["(2^8)"] = [int(len(cand)), int(ok.sum())]
    out.append(cand[ok])
    # type 3: odd
    cands = []
    for c in code:
        x = [a ^ b for a, b in zip(c, x0)]
        b = np.array([1 if xi == 0 else -1 for xi in x], dtype=np.int64)
        rep = np.tile(b, (n, 1))
        for i in range(n):
            rep[i, i] = -3 if b[i] == 1 else 3
        cands.append(rep)
    cand = np.concatenate(cands, axis=0)
    ok = F.member(cand)
    counts["(3,1^23)"] = [int(len(cand)), int(ok.sum())]
    out.append(cand[ok])
    # shorter vectors: even (+-4 e_i), odd base vectors of norm 24
    short = int(F.member(enumerate_shape(n, [4])).sum())
    bases = np.array([[1 if (a ^ b) == 0 else -1 for a, b in zip(c, x0)] for c in code], dtype=np.int64)
    short += int(F.member(bases).sum())
    W = np.concatenate(out, axis=0)
    return W, {"code_weights": dict(sorted(wts.items())), "shapes": counts, "count": int(len(W)),
               "shorter_nonzero_vectors": short, "covolume_of_4Gamma": covol_k,
               "covolume_Gamma": str(Fraction(covol_k, 4 ** n))}


# ---------------- strains and velocities ----------------

def project_bar(Ck, k, Y):
    """Frobenius-orthogonal projection of Y onto {X : r_i X c_i^T = 0}. Exact."""
    n = len(Ck)
    C = [[Fraction(Ck[i][j], k) for j in range(n)] for i in range(n)]
    R = [[C[i][j] + (2 if i == j else 0) for j in range(n)] for i in range(n)]
    rr = [[sum(R[i][t] * R[j][t] for t in range(n)) for j in range(n)] for i in range(n)]
    cc = [[sum(C[i][t] * C[j][t] for t in range(n)) for j in range(n)] for i in range(n)]
    G = [[rr[i][j] * cc[i][j] for j in range(n)] for i in range(n)]
    b = [sum(R[i][a] * Y[a][c] * C[i][c] for a in range(n) for c in range(n)) for i in range(n)]
    Ginv, _ = frac_inverse(G)
    alpha = [sum(Ginv[i][j] * b[j] for j in range(n)) for i in range(n)]
    X = [[Y[a][c] - sum(alpha[j] * R[j][a] * C[j][c] for j in range(n)) for c in range(n)] for a in range(n)]
    for i in range(n):
        t = sum(R[i][a] * X[a][c] * C[i][c] for a in range(n) for c in range(n))
        need(t == 0, "tangency failed")
    return X, R, C


def velocities(F, Wk, X):
    """For every min vector w (k*w in Wk) and every motif ball p: find q, m, classify.
    Returns counts and the exact minimum non-bar velocity, plus list of negatives."""
    n, k = F.n, F.k
    den = 1
    for row in X:
        for q in row:
            den = den * q.denominator // __import__("math").gcd(den, q.denominator)
    Xn = [[int(X[a][c] * den) for c in range(n)] for a in range(n)]
    # y = X w^T  ->  y_int = Xn (k w)^T ; velocity * k^2 * den = (kw).y_int - k (v . y_int)
    Wobj = Wk.astype(object)
    Xobj = np.array(Xn, dtype=object)
    Y = Wobj.dot(Xobj.T)            # (N, n): row r = Xn @ (k w)
    Q = (Wobj * Y).sum(axis=1)      # (kw) . y_int
    e0k = np.zeros(n, dtype=np.int64)
    cw = (Wk @ F.adj) % F.mod
    counts = {"intra": 0, "inter": 0, "zero": 0, "neg": 0}
    min_pos = None
    neg_list = []
    zero_list = []
    for pi, p in enumerate(F.P):
        ip, sp = pi // 2, (1 if pi % 2 == 0 else -1)
        pk_row = np.array([k * x for x in p], dtype=np.int64)
        cl = (cw + (pk_row @ F.adj)) % F.mod
        h = F.hash(cl)
        qidx = np.full(len(Wk), -1, dtype=np.int64)
        for hv, qi in F.hash_to_p.items():
            sel = h == hv
            qidx[sel] = qi
        need((qidx >= 0).all(), "some (w,p) has no motif partner")
        need((cl == F.Pcls[qidx]).all(), "class mismatch after hash lookup")
        iq = qidx // 2
        sq = np.where(qidx % 2 == 0, 1, -1)
        # intra: x = w + p - q == 0
        Xk = Wk + pk_row - np.array([[k * x for x in F.P[q]] for q in range(2 * n)], dtype=np.int64)[qidx]
        intra = ~Xk.any(axis=1)
        counts["intra"] += int(intra.sum())
        inter = ~intra
        counts["inter"] += int(inter.sum())
        rows = np.nonzero(inter)[0]
        yq = Y[rows, iq[rows]]
        yp = Y[rows, ip]
        vel = Q[rows] - k * (sq[rows].astype(object) * yq - sp * yp)
        neg = np.array([v < 0 for v in vel])
        zer = np.array([v == 0 for v in vel])
        counts["neg"] += int(neg.sum())
        counts["zero"] += int(zer.sum())
        for r in rows[neg]:
            neg_list.append((pi, int(qidx[r]), Wk[r].tolist()))
        for r in rows[zer]:
            zero_list.append((pi, int(qidx[r]), Wk[r].tolist()))
        pos = [v for v in vel if v > 0]
        if pos:
            m = min(pos)
            if min_pos is None or m < min_pos:
                min_pos = m
    scale = k * k * den
    # bars: (p = +e_i, q = -e_i, x = r_i) or reversed
    bar_like = 0
    for (pi, qi, wk) in zero_list:
        ip, iq = pi // 2, qi // 2
        if ip == iq and pi != qi:
            # w = x + q - p ; for bar i: x = +-r_i, q - p = -+2 e_i, w = +-c_i
            ck = F.Ck[ip]
            if wk == ck or wk == [-x for x in ck]:
                bar_like += 1
    return counts, Fraction(min_pos, scale), neg_list, zero_list, bar_like, den.bit_length()


def main():
    skip_leech = "--skip-leech" in sys.argv
    T = load_tables()
    print("hash seed", HASH_SEED)
    report = {}
    # ---------- BW16 ----------
    F16 = Framework(16, 2, T["C2_16_WITNESS"])
    report["BW16_setup"] = F16.setup_cosets()
    W16, info16 = bw16_min_vectors(F16)
    report["BW16_minvecs"] = info16
    I16 = [[Fraction(int(i == j)) for j in range(16)] for i in range(16)]
    X16, R16, C16 = project_bar(F16.Ck, 2, I16)
    cnt, delta, negs, zeros, barlike, denbits = velocities(F16, W16, X16)
    report["BW16_vel_projI"] = {"counts": cnt, "delta": str(delta), "delta_float": float(delta),
                                "zeros_that_are_bars": barlike, "X_den_bits": denbits}
    problems = []
    if not (info16["count"] == 4320 and info16["shorter_nonzero_vectors"] == 0
            and report["BW16_setup"]["index_Gamma_over_Lambda"] == 32 and report["BW16_setup"]["det_L"] == "2"):
        problems.append("BW16 lattice (4320 minimal vectors, index 32, det 2)")
    if not (cnt["inter"] == 137280 and cnt["neg"] == 0 and cnt["zero"] == 32 and barlike == 32
            and delta > Fraction(1, 7)):
        problems.append("BW16 velocities (137280 contacts, 0 negative, 32 bar zeros, delta > 1/7)")
    summary = "BW16 4320 min vectors, 0 negative and 32 bar zeros of 137280 contacts"
    if not skip_leech:
        F24 = Framework(24, 4, T["U24_WITNESS"])
        report["Leech_setup"] = F24.setup_cosets()
        W24, info24 = leech_min_vectors(F24)
        report["Leech_minvecs"] = info24
        I24 = [[Fraction(int(i == j)) for j in range(24)] for i in range(24)]
        for label, Y in (("projI", I24),
                         ("team_seed", [[Fraction(T["X0_24_INT_256"][i][j], 256) for j in range(24)] for i in range(24)])):
            X24, _, _ = project_bar(F24.Ck, 4, Y)
            cnt, delta, negs, zeros, barlike, denbits = velocities(F24, W24, X24)
            entry = {"counts": cnt, "delta": str(delta), "delta_float": float(delta),
                     "zeros_that_are_bars": barlike, "X_den_bits": denbits}
            if negs:
                entry["negatives_sample"] = negs[:6]
                entry["negatives_distinct_w_up_to_sign"] = len({tuple(abs(x) for x in w) for _, _, w in negs})
            report["Leech_vel_" + label] = entry
        if not (info24["count"] == 196560 and info24["shorter_nonzero_vectors"] == 0
                and report["Leech_setup"]["index_Gamma_over_Lambda"] == 48
                and report["Leech_setup"]["det_L"] == "3/256"):
            problems.append("Leech lattice (196560 minimal vectors, index 48, det 3/256)")
        vp, vt = report["Leech_vel_projI"], report["Leech_vel_team_seed"]
        if not (vp["counts"]["neg"] == 28 and vp["counts"]["inter"] == 9432672):
            problems.append("natural Leech seed should show 28 negative contacts")
        if not (vt["counts"]["inter"] == 9432672 and vt["counts"]["neg"] == 0 and vt["counts"]["zero"] == 48
                and vt["zeros_that_are_bars"] == 48 and Fraction(vt["delta"]) >= Fraction(2, 25)):
            problems.append("Leech target-seed velocities (0 negative, 48 bar zeros, delta >= 2/25)")
        summary += "; Leech 196560 min vectors, target seed 0 negative and 48 bar zeros of 9432672, natural seed 28 negative"
    txt = json.dumps(report, sort_keys=True, indent=1, default=str)
    print(txt)
    print("SHA256", hashlib.sha256(txt.encode()).hexdigest())
    if problems:
        raise SystemExit("CHECK FAILED: " + "; ".join(problems))
    print("RESULT leech_sheaf/adv_lattice: PASS " + summary)


if __name__ == "__main__":
    main()
