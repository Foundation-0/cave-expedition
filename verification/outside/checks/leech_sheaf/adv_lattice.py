#!/usr/bin/env python3
"""Rebuild of the AUDIT-020R lattices and exact contact velocities (advocate check).

Reads only the data tables C2_16_WITNESS, U24_WITNESS and X0_24_INT_256 from the target's
verifier, as data (the target's code is never run). Everything else is rebuilt here: the
coset map from the integer adjugate, lattice closure, exhaustive minimal-vector
enumeration (BW16 4,320, Leech 196,560, none shorter), contact assignment, and first-order
velocities of every contact in exact integers. It also shows that the natural Leech seed
(projection of the identity) fails on 28 contacts, while the target's seed has 0 negative
and 48 zero contacts that are exactly the bars.
Backs: AUDIT-020R, VERDICTS.md section 1 row "Barnes-Wall and Leech realizations and
arcs", and the section 3 repair "Leech seed: the canonical choice fails on 28 contacts".
Needs: Python 3, numpy, a clone of the target at the head of draft PR 106
(first argument, or environment variable INCENTRE_LATTICES_PR106).
Run: python3 -I -B adv_lattice.py /path/to/incentre-lattices [--skip-leech]
Time: about 1 minute. The only random numbers are a lookup hash with seed 12345 (printed);
every hash hit is rechecked exactly, so the seed cannot change a result. Writes no files.
"""
